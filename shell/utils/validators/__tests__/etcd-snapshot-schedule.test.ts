import { isValidEtcdSnapshotSchedule } from '@shell/utils/validators/etcd-snapshot-schedule';

describe('isValidEtcdSnapshotSchedule', () => {
  it.each([
    '0 */5 * * *',
    '0 */12 * * *',
    '* * * * *',
    '0 0 * * 0',
    '0 0 * * 6',
    '*/5 * * * *',
    '0/5 * * * *',
    '5/15 * * * *',
    '1-5/2 * * * *',
    '1,2,3 * * * *',
    '*/60 * * * *',
    '0 0 * * */7',
    '0 0 * * MON',
    '0 0 * * mon',
    '0 0 * * Mon',
    '0 0 * * MON-FRI',
    '0 0 * * mon-fri',
    '0 0 * * MON,WED,FRI',
    '0 0 * * SUN',
    '0 0 * JAN *',
    '0 0 * jan *',
    '0 0 * JAN-MAR *',
    '0 0 1 JAN,JUN *',
    '@yearly',
    '@annually',
    '@monthly',
    '@weekly',
    '@daily',
    '@midnight',
    '@hourly',
    '0 0 ? * MON',
    '0 0 1 * ?',
    '0 0 ? * ?',
    '? ? ? ? ?',
    '00 00 * * *',
    '007 * * * *',
    ' 0 0 * * *',
    '0 0 * * * ',
    '0  0 * * *',
    '0 0 31 2 *',
    '1,,3 * * * *',
    '1, * * * *',
    '+1 * * * *',
    '*-5 * * * *',
    '?/2 * * * *',
    '@every 6h',
    '@every 1h30m',
    '@every .5h',
    '@every 1.h',
    '@every 0s',
    '@every 500ms',
    'CRON_TZ=UTC 0 0 * * *',
    'TZ=UTC 0 0 * * *',
    'CRON_TZ=UTC @daily',
    'TZ=UTC @every 6h',
    'TZ=UTC @daily ',
    'CRON_TZ=Asia/Tokyo 0 6 * * *',
  ])('should accept %p', (schedule) => {
    expect(isValidEtcdSnapshotSchedule(schedule)).toBe(true);
  });

  it.each([
    '0 0 * * 7',
    '0 0 * * 1-7',
    '0 0 * * 5-7',
    '0 0 * * 0,7',
    'TZ=UTC',
    'CRON_TZ=UTC',
    'TZ=UTC\t@daily',
    '* * * * * *',
    '* * * *',
    '0 0 * * * 2026',
    '60 * * * *',
    '0 24 * * *',
    '0 0 0 * *',
    '0 0 32 * *',
    '0 0 * 0 *',
    '0 0 * 13 *',
    '0 0 * * 8',
    '*/0 * * * *',
    '-1 * * * *',
    '5-1 * * * *',
    '0 22-2 * * *',
    '0 0 * * FRI-MON',
    '1-2-3 * * * *',
    '1/2/3 * * * *',
    ', * * * *',
    '0 0 L * *',
    '0 0 * * 5L',
    '0 0 * * 1#1',
    '0 0 15W * *',
    'H * * * *',
    '@reboot',
    '1.5 * * * *',
    '0x10 * * * *',
    '@every',
    '@every 90',
    '@every 1d',
    '@every  6h',
    '@every -1h',
    '@every 999999999h',
    'CRON_TZ=UTC * * * * * *',
    '@DAILY',
    '@Daily',
    '@foo',
    '@daily ',
    ' @daily',
    'not-a-cron',
    'daily',
    '   ',
    '',
  ])('should reject %p', (schedule) => {
    expect(isValidEtcdSnapshotSchedule(schedule)).toBe(false);
  });
});
